"""Generates src/lib/cities.ts from GeoNames cities15000.txt (CC BY 4.0, https://www.geonames.org/).

Usage: python -X utf8 scripts/gen-cities.py <path-to-cities15000.txt>

Keeps populated places of 50,000 people or more (excluding sections of larger cities), as
[geonameid, name, country code, region, lat, lon, tz index]. Region is the state/province code
for the US, Canada and Australia, where city names repeat a lot. Coordinates are rounded to
two decimals (about a kilometre): a city, never an address.

If this file is regenerated, the database `places` table must be regenerated too (new migration).
"""
import csv, json, sys

MIN_POP = 50000
src = sys.argv[1]
rows = []
with open(src, encoding='utf-8') as f:
    for r in csv.reader(f, delimiter='\t', quoting=csv.QUOTE_NONE):
        pop = int(r[14] or 0)
        if pop < MIN_POP or r[7] == 'PPLX' or not r[17]:
            continue
        region = r[10] if r[8] in ('US', 'CA', 'AU') and r[10].isalpha() and len(r[10]) <= 3 else ''
        if r[8] == 'CA':  # GeoNames uses numbers for Canadian provinces
            region = {'01': 'AB', '02': 'BC', '03': 'MB', '04': 'NB', '05': 'NL', '07': 'NS', '08': 'ON', '09': 'PE', '10': 'QC', '11': 'SK', '12': 'YT', '13': 'NT', '14': 'NU'}.get(r[10], '')
        if r[8] == 'AU':
            region = {'01': 'ACT', '02': 'NSW', '03': 'NT', '04': 'QLD', '05': 'SA', '06': 'TAS', '07': 'VIC', '08': 'WA'}.get(r[10], '')
        rows.append((int(r[0]), r[1], r[8], region, round(float(r[4]), 2), round(float(r[5]), 2), r[17], pop))

rows.sort(key=lambda x: -x[7])  # biggest first, so search and ties favour the better-known city
tzs = sorted({r[6] for r in rows})
tzi = {t: i for i, t in enumerate(tzs)}
out = [[r[0], r[1], r[2], r[3], r[4], r[5], tzi[r[6]]] for r in rows]

with open('src/lib/cities.ts', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by scripts/gen-cities.py from GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/). Do not edit.\n')
    f.write('// [geonameid, name, country code, region, lat, lon, index into CITY_TZS], largest first.\n')
    f.write('export type RawCity = [number, string, string, string, number, number, number];\n')
    f.write('export const CITY_TZS: string[] = ' + json.dumps(tzs, separators=(',', ':')) + ';\n')
    f.write('export const RAW_CITIES: RawCity[] = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out), 'cities,', len(tzs), 'time zones')
