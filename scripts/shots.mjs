// Visual QA: opens several visitors in different time zones, makes them interact, and saves screenshots.
// Usage: node scripts/shots.mjs [url] [outDir]
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const url = process.argv[2] ?? 'http://localhost:5173/';
const out = process.argv[3] ?? 'test-results/shots';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
async function visitor(tz, viewport, extra = {}) {
  const ctx = await browser.newContext({ timezoneId: tz, viewport, deviceScaleFactor: extra.dpr ?? 1, isMobile: !!extra.mobile, hasTouch: !!extra.mobile });
  const page = await ctx.newPage();
  page.on('console', (m) => { if (m.type() === 'error') console.log(`[${tz}] ${m.text()}`); });
  await page.goto(url + '?hq', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForFunction(() => window.__onesky?.sky.online, null, { timeout: 90000 });
  return page;
}
async function enter(page) {
  await page.locator('#btn-enter').click();
  await page.waitForFunction(() => window.__onesky.entered, null, { timeout: 30000 });
  await page.waitForFunction(() => !document.getElementById('app').classList.contains('is-hidden'), null, { timeout: 30000 });
}
const desk = { width: 1440, height: 900 };
const a = await visitor('America/Chicago', desk);
await wait(4500);
await a.screenshot({ path: `${out}/01-arrival.png` });
const b = await visitor('Africa/Lagos', desk);
const c = await visitor('Asia/Tokyo', desk);
const m = await visitor('Europe/Paris', { width: 390, height: 844 }, { mobile: true, dpr: 2 });
await wait(3500);
await m.screenshot({ path: `${out}/02-mobile-arrival.png` });
await Promise.all([enter(b), enter(c)]);
await a.locator('#btn-enter').click();
await wait(2600);
await a.screenshot({ path: `${out}/03-interlude.png` });
await a.waitForFunction(() => !document.getElementById('app').classList.contains('is-hidden'), null, { timeout: 30000 });
await enter(m);
await wait(9500);
await a.screenshot({ path: `${out}/04-home.png` });
await m.screenshot({ path: `${out}/05-mobile-home.png` });
const ub = await b.evaluate(() => window.__onesky.sky.uid);
const ua = await a.evaluate(() => window.__onesky.sky.uid);
await a.evaluate((id) => window.__onesky.select({ type: 'light', id }), ub);
await wait(1800);
await a.screenshot({ path: `${out}/06-person-card.png` });
await a.locator('#card button.btn.primary').click();
await wait(1400);
await a.screenshot({ path: `${out}/07-wave-flying.png` });
await wait(3500);
await b.screenshot({ path: `${out}/08-wave-received.png` });
await b.locator('.toast button').click({ timeout: 60000 });
await wait(6500);
await a.screenshot({ path: `${out}/09-threaded.png` });
await a.evaluate(() => { window.__onesky.select(null); window.__onesky.globe.flyTo(30, -30, 3.6, 800); });
await wait(2500);
await a.screenshot({ path: `${out}/10-thread-atlantic.png` });
const lid = await a.evaluate(() => [...window.__onesky.lanterns.keys()][0]);
await a.evaluate((id) => window.__onesky.select({ type: 'lantern', id }), lid);
await wait(2200);
await a.screenshot({ path: `${out}/11-lantern-card.png` });
await m.evaluate((id) => window.__onesky.select({ type: 'lantern', id }), lid);
await wait(2200);
await m.screenshot({ path: `${out}/12-mobile-lantern.png` });
await a.evaluate(() => window.__onesky.select(null));
await a.locator('#btn-lantern').click();
await wait(700);
await a.screenshot({ path: `${out}/13-composer.png` });
await a.keyboard.press('Escape');
await a.evaluate(() => window.__onesky.globe.flyTo(20, 10, 1.9, 800));
await wait(2500);
await a.screenshot({ path: `${out}/14-close-up.png` });
await a.locator('#btn-postcard').click();
await wait(1500);
await a.screenshot({ path: `${out}/15-postcard.png` });
await a.keyboard.press('Escape');
await a.locator('#btn-about').click();
await wait(700);
await a.screenshot({ path: `${out}/16-about.png` });
await browser.close();
console.log('shots saved to', out);
